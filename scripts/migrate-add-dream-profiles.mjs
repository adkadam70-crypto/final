// Creates the dreamProfiles table for the "Build Your Dream" feature — one
// row per user, updated in place as they move through onboarding and the
// country workspace (see lib/db/schema.ts and app/actions/dream.ts). Same
// raw-SQL approach as every other migrate-*.mjs — drizzle-kit push hangs on
// introspection in this environment.
//
// Usage: node --env-file=.env.local scripts/migrate-add-dream-profiles.mjs

import { neon } from '@neondatabase/serverless'

const sql = neon(process.env.DATABASE_URL)

await sql`
  CREATE TABLE IF NOT EXISTS "dreamProfiles" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "userId" uuid NOT NULL UNIQUE,
    "strengths" jsonb NOT NULL DEFAULT '[]'::jsonb,
    "hobbies" text NOT NULL DEFAULT '',
    "interests" jsonb NOT NULL DEFAULT '[]'::jsonb,
    "interestsOther" text NOT NULL DEFAULT '',
    "country" text,
    "recommendedField" text,
    "recommendedFieldRationale" text,
    "confirmedField" text,
    "analysisStrengths" jsonb,
    "analysisGaps" jsonb,
    "checklist" jsonb NOT NULL DEFAULT '{}'::jsonb,
    "createdAt" timestamp NOT NULL DEFAULT now(),
    "updatedAt" timestamp NOT NULL DEFAULT now()
  )
`

console.log('Created dreamProfiles table.')
