// Splits the old single-country dreamProfiles row into the new
// dreamCountryProfiles table (one row per user+country), so a student can
// build multiple countries off the same onboarding/field. Migrates any
// existing country/analysis/checklist data out of dreamProfiles first, then
// drops those now-unused columns from it. Same raw-SQL approach as every
// other migrate-*.mjs — drizzle-kit push hangs on introspection here.
//
// Usage: node --env-file=.env.local scripts/migrate-add-dream-country-profiles.mjs

import { neon } from '@neondatabase/serverless'

const sql = neon(process.env.DATABASE_URL)

await sql`
  CREATE TABLE IF NOT EXISTS "dreamCountryProfiles" (
    "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "userId" uuid NOT NULL,
    "country" text NOT NULL,
    "analysisStrengths" jsonb,
    "analysisGaps" jsonb,
    "checklist" jsonb NOT NULL DEFAULT '{}'::jsonb,
    "createdAt" timestamp NOT NULL DEFAULT now(),
    "updatedAt" timestamp NOT NULL DEFAULT now()
  )
`
await sql`CREATE UNIQUE INDEX IF NOT EXISTS "dreamCountryProfiles_user_country_idx" ON "dreamCountryProfiles" ("userId", "country")`

// Carry over any existing single-country row's data (old checklist was
// boolean-per-item; true -> 100, false/missing -> not carried since a false
// entry is indistinguishable from "never touched" and the auto-detect pass
// will recompute real signal anyway).
const existing = await sql`SELECT "userId", country, "analysisStrengths", "analysisGaps", checklist FROM "dreamProfiles" WHERE country IS NOT NULL`
for (const row of existing) {
  const oldChecklist = row.checklist ?? {}
  const newChecklist = Object.fromEntries(Object.entries(oldChecklist).filter(([, v]) => v === true).map(([k]) => [k, 100]))
  await sql`
    INSERT INTO "dreamCountryProfiles" ("userId", country, "analysisStrengths", "analysisGaps", checklist)
    VALUES (${row.userId}, ${row.country}, ${JSON.stringify(row.analysisStrengths ?? null)}::jsonb, ${JSON.stringify(row.analysisGaps ?? null)}::jsonb, ${JSON.stringify(newChecklist)}::jsonb)
    ON CONFLICT ("userId", country) DO NOTHING
  `
}
console.log(`Migrated ${existing.length} existing dream profile row(s) into dreamCountryProfiles.`)

await sql`ALTER TABLE "dreamProfiles" DROP COLUMN IF EXISTS country`
await sql`ALTER TABLE "dreamProfiles" DROP COLUMN IF EXISTS "analysisStrengths"`
await sql`ALTER TABLE "dreamProfiles" DROP COLUMN IF EXISTS "analysisGaps"`
await sql`ALTER TABLE "dreamProfiles" DROP COLUMN IF EXISTS checklist`

console.log('Dropped now-unused country/analysis/checklist columns from dreamProfiles.')
