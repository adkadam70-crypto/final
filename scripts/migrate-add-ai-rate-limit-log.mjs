// Generic rate-limit ledger for AI-calling actions that don't already have
// their own per-call history table to count against (unlike runMatch and
// analyzeTargetUniversity, which reuse their existing matches/
// universityAnalyses insert logs — see lib/rate-limit.ts). Starts with
// analyzeProfileStrength; reusable for any future AI action.
//
// Usage: node --env-file=.env.local scripts/migrate-add-ai-rate-limit-log.mjs

import { neon } from '@neondatabase/serverless'

const sql = neon(process.env.DATABASE_URL)

await sql`
  CREATE TABLE IF NOT EXISTS "aiRateLimitLog" (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "userId" uuid NOT NULL,
    action text NOT NULL,
    "createdAt" timestamp NOT NULL DEFAULT now()
  )
`
await sql`CREATE INDEX IF NOT EXISTS "aiRateLimitLog_userId_action_idx" ON "aiRateLimitLog" ("userId", action, "createdAt")`

console.log('Created aiRateLimitLog table.')
